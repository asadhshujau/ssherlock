//! Typed identifiers for every persisted model.
//!
//! An [`Id<T>`] is a UUID v7 tagged with the type it identifies, so an `Id<Host>` cannot be
//! passed where an `Id<Key>` is expected. v7 ids start with a millisecond timestamp, so they
//! sort by creation time and keep SQLite indexes append-friendly.

use std::any::type_name;
use std::cmp::Ordering;
use std::fmt;
use std::hash::{Hash, Hasher};
use std::marker::PhantomData;
use std::str::FromStr;

use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// A unique identifier for a value of type `T`.
///
/// Serialises as the hyphenated UUID string, which is also how it is stored in SQLite (`TEXT`).
/// The type tag exists only at compile time:
///
/// ```compile_fail
/// use ssherlock_core::Id;
/// struct Host;
/// struct Key;
/// let host: Id<Host> = Id::generate();
/// let key: Id<Key> = host; // error: mismatched types
/// ```
#[derive(Serialize, Deserialize)]
#[serde(transparent, bound = "")]
pub struct Id<T> {
    uuid: Uuid,
    // `fn() -> T` keeps `Id<T>` `Send + Sync + Copy` whatever `T` is, and doesn't make the
    // id own a `T` for drop-check purposes.
    #[serde(skip)]
    marker: PhantomData<fn() -> T>,
}

impl<T> Id<T> {
    /// Creates a new, unique id from the current time and random bits (UUID v7).
    ///
    /// Ids generated by one process are strictly increasing, even within the same millisecond.
    pub fn generate() -> Self {
        Self::from_uuid(Uuid::now_v7())
    }

    /// Wraps an existing UUID, e.g. one read back from the database.
    ///
    /// Any UUID version is accepted: the type tag carries the meaning, the version only affects
    /// how new ids are generated.
    pub const fn from_uuid(uuid: Uuid) -> Self {
        Self {
            uuid,
            marker: PhantomData,
        }
    }

    /// The underlying UUID.
    pub const fn as_uuid(&self) -> &Uuid {
        &self.uuid
    }
}

/// Why a string could not be turned into an [`Id`].
#[derive(Debug, thiserror::Error)]
pub enum IdError {
    /// The input is not a UUID in any format the `uuid` crate accepts.
    #[error("could not parse an id from {input:?}")]
    Parse {
        /// The rejected input.
        input: String,
        /// What the UUID parser objected to.
        #[source]
        source: uuid::Error,
    },
}

impl<T> FromStr for Id<T> {
    type Err = IdError;

    fn from_str(input: &str) -> Result<Self, Self::Err> {
        Uuid::parse_str(input)
            .map(Self::from_uuid)
            .map_err(|source| IdError::Parse {
                input: input.to_owned(),
                source,
            })
    }
}

impl<T> fmt::Display for Id<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.uuid.hyphenated().fmt(f)
    }
}

impl<T> fmt::Debug for Id<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // `Id<Host>(0190…)` rather than the full module path of `Host`.
        let full = type_name::<T>();
        let short = full.rsplit("::").next().unwrap_or(full);
        write!(f, "Id<{short}>({})", self.uuid.hyphenated())
    }
}

// The traits below are written by hand because `derive` would require `T` to implement them
// too, and `T` is only a tag.

impl<T> Clone for Id<T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T> Copy for Id<T> {}

impl<T> PartialEq for Id<T> {
    fn eq(&self, other: &Self) -> bool {
        self.uuid == other.uuid
    }
}

impl<T> Eq for Id<T> {}

impl<T> PartialOrd for Id<T> {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl<T> Ord for Id<T> {
    fn cmp(&self, other: &Self) -> Ordering {
        self.uuid.cmp(&other.uuid)
    }
}

impl<T> Hash for Id<T> {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.uuid.hash(state);
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]

    use std::collections::HashSet;

    use pretty_assertions::assert_eq;

    use super::*;

    /// A tag type that implements none of the traits `Id` provides.
    struct Host;

    #[test]
    fn generated_ids_are_v7_unique_and_increasing() {
        let ids: Vec<Id<Host>> = (0..1_000).map(|_| Id::generate()).collect();

        assert!(ids.iter().all(|id| id.as_uuid().get_version_num() == 7));
        // Unique + sorted = strictly increasing.
        assert_eq!(ids.iter().collect::<HashSet<_>>().len(), ids.len());
        assert!(ids.is_sorted());
    }

    #[test]
    fn parse_accepts_uuid_formats() {
        let canonical = "01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f";
        let cases = [
            ("hyphenated", canonical),
            ("simple", "01936f4e7a2b7c3d8e4f5a6b7c8d9e0f"),
            ("upper case", "01936F4E-7A2B-7C3D-8E4F-5A6B7C8D9E0F"),
            ("urn", "urn:uuid:01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f"),
            ("braced", "{01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f}"),
            ("v4", "6f1c2b9e-3d4a-4b5c-9d8e-7f6a5b4c3d2e"),
        ];

        for (name, input) in cases {
            let id: Result<Id<Host>, _> = input.parse();
            assert!(id.is_ok(), "{name}: {input:?} should parse");
        }
        let id: Id<Host> = canonical.parse().unwrap();
        assert_eq!(id.to_string(), canonical);
    }

    #[test]
    fn parse_rejects_non_uuids() {
        let cases = [
            ("empty", ""),
            ("too short", "01936f4e-7a2b-7c3d-8e4f"),
            ("not hex", "zzzzzzzz-7a2b-7c3d-8e4f-5a6b7c8d9e0f"),
            ("trailing junk", "01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f!"),
            ("label", "prod-db-1"),
        ];

        for (name, input) in cases {
            let err = input.parse::<Id<Host>>().unwrap_err();
            let IdError::Parse {
                input: rejected, ..
            } = &err;
            assert_eq!(rejected, input, "{name}");
            assert!(err.to_string().starts_with("could not parse an id from"));
        }
    }

    #[test]
    fn display_and_parse_round_trip() {
        let id: Id<Host> = Id::generate();
        assert_eq!(id.to_string().parse::<Id<Host>>().unwrap(), id);
    }

    #[test]
    fn serde_uses_the_plain_uuid_string() {
        let id: Id<Host> = "01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f".parse().unwrap();

        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, r#""01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f""#);
        assert_eq!(serde_json::from_str::<Id<Host>>(&json).unwrap(), id);
        assert!(serde_json::from_str::<Id<Host>>(r#""nope""#).is_err());
    }

    #[test]
    fn debug_names_the_tag_type() {
        let id: Id<Host> = "01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f".parse().unwrap();
        assert_eq!(
            format!("{id:?}"),
            "Id<Host>(01936f4e-7a2b-7c3d-8e4f-5a6b7c8d9e0f)"
        );
    }

    #[test]
    fn id_is_copy_send_sync_for_any_tag() {
        // `Rc` is neither `Send` nor `Sync`; the id must be both anyway.
        fn assert_traits<X: Copy + Send + Sync + 'static>() {}
        assert_traits::<Id<std::rc::Rc<Host>>>();
    }
}
